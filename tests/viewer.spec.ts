test('directory, filters, navigation, export, and private wiki', async ({ page }) => {
  const errors:string[]=[];
  page.on('pageerror', e=>errors.push(e.message));
  await page.addInitScript(()=>document.addEventListener('securitypolicyviolation', e=>{throw new Error('CSP: '+e.violatedDirective);}));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Funds',exact:true})).toBeVisible();
  await expect(page.getByRole('table')).toBeVisible();
  await expect(page.locator('.funds-table tbody tr:not(.fund-group)')).toHaveCount(50);
  await page.screenshot({path:'tmp/viewer-desktop.png',fullPage:true});
  await expect(page.locator('.fund-group')).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Next page'})).toHaveCount(0);
  const firstFund=await page.locator('.fund-name').first().textContent();
  await page.getByRole('checkbox',{name:'Select loaded funds'}).check();
  await page.locator('.funds-table-scroll').evaluate(el=>{el.scrollTop=el.scrollHeight;});
  await expect(page.locator('.funds-table tbody tr:not(.fund-group)')).toHaveCount(100);
  await expect(page.locator('.fund-name').first()).toHaveText(firstFund!);
  await expect(page.locator('.funds-results')).toContainText('50 selected');
  await page.locator('.funds-table-scroll').evaluate(el=>{el.scrollTop=el.scrollHeight;});
  await expect(page.locator('.funds-table tbody tr:not(.fund-group)')).toHaveCount(150);
  await page.getByRole('button',{name:'Clear',exact:true}).click();
  await page.getByRole('searchbox').fill('a16z.com');
  await expect(page.locator('.funds-table tbody tr:not(.fund-group)')).toHaveCount(1);
  await page.getByRole('table').getByRole('link',{name:/Andreessen/i}).click();
  await expect(page.locator('article')).toContainText('Andreessen');
  await expect(page.locator('.track-note')).toContainText('uv run fundraising-buddy track');
  await page.getByRole('link',{name:'Back to funds'}).click();
  await page.getByRole('button',{name:'Fund',exact:true}).click();
  await expect(page.getByRole('columnheader',{name:'Fund',exact:true})).toHaveAttribute('aria-sort','descending');
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export domains'}).click();
  expect((await download).suggestedFilename()).toBe('investor-domains.txt');
  await page.getByRole('link',{name:'People',exact:true}).click();
  await expect(page.getByRole('heading',{name:'People',exact:true})).toBeVisible();
  await page.getByRole('link',{name:'Your pipeline',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Your pipeline'})).toBeVisible();
  await page.getByRole('link',{name:'Your wiki',exact:true}).click();
  await page.getByRole('row').filter({has:page.getByRole('cell',{name:'Home',exact:true})}).getByRole('button').click();
  await expect(page.locator('article')).toBeVisible();
  await page.getByRole('button',{name:'Refresh',exact:true}).click();
  await expect(page.locator('article')).toBeVisible();
  expect(errors).toEqual([]);
});

